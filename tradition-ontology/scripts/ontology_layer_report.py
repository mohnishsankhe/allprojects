"""Ontology layer, step 4: coverage report and extraction queue.

  python3 scripts/ontology_layer_report.py

Reads ontology_layer/register/texts.jsonl, whys.jsonl, results.jsonl, gaps.jsonl (run the merge first) and writes
ontology_layer/COVERAGE.md, ontology_layer/QUEUE.md and ontology_layer/coverage.json.
"""
import collections
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LAYER = os.path.join(ROOT, 'ontology_layer')
LEVELS = ['text-verified', 'sourced', 'skeleton', 'outline']
LAYER_TAGS = ['L0', 'L1', 'L2', 'L3', 'L4', 'L5', 'L6', 'L7', 'M', 'W']
LAYER_NAMES = {'L0': 'Gate', 'L1': 'Body', 'L2': 'Breath and the capacity to act', 'L3': 'Map', 'L4': 'Mind',
               'L5': 'Drives and seeds', 'L6': 'Resolve and action', 'L7': 'Knower and readiness', 'M': 'Method',
               'W': 'World model only'}


def load(name):
    p = os.path.join(LAYER, name)
    return [json.loads(line) for line in open(p, encoding='utf-8') if line.strip()] if os.path.exists(p) else []


def pct(a, b):
    return f'{(100 * a / b):.0f}%' if b else '–'


def main():
    texts = load('register/texts.jsonl')
    whys, results, gaps = load('whys.jsonl'), load('results.jsonl'), load('gaps.jsonl')
    byn = {t['n']: t for t in texts}
    lv_w = collections.Counter(w['verification']['level'] for w in whys)
    lv_r = collections.Counter(r['verification']['level'] for r in results)
    # by layer
    lay_w = collections.defaultdict(collections.Counter)
    lay_r = collections.defaultdict(collections.Counter)
    for w in whys:
        for t in w.get('layers') or []:
            lay_w[t][w['verification']['level']] += 1
    for r in results:
        for t in r.get('layers') or []:
            lay_r[t][r['verification']['level']] += 1
    # by row
    row_w = collections.defaultdict(list)
    row_r = collections.defaultdict(list)
    for w in whys:
        for n in w.get('rows') or []:
            row_w[n].append(w)
    for r in results:
        row_r[r.get('row')].append(r)
    # results reaching a why
    reach = sum(1 for r in results if r.get('rests_on'))
    link_types = collections.Counter(link.get('link') for r in results for link in r.get('rests_on') or [])
    restricted = sum(1 for r in results if r.get('restricted'))
    kinds = collections.Counter(r.get('kind') for r in results)
    fam_w = collections.Counter(w['id'].split(':')[1] for w in whys)
    fam_r = collections.Counter(r['id'].split(':')[1] for r in results)
    # rows with nothing
    empty_study = [t for t in texts if t['tier'] == 'Study' and not row_w[t['n']] and not row_r[t['n']]]
    empty_read = [t for t in texts if t['tier'] == 'Read' and not row_r[t['n']] and not row_w[t['n']]]
    L = []
    L.append('# Ontology layer: coverage\n')
    L.append('Generated by `scripts/ontology_layer_report.py` from the merged layer. Verification is computed from the '
             'teachings each entry cites (SCHEMA.md, "Verification").\n')
    L.append('## Totals\n')
    L.append('| | Count | text-verified | sourced | skeleton | outline |')
    L.append('|---|---|---|---|---|---|')
    L.append(f"| Whys | {len(whys)} | " + ' | '.join(f"{lv_w[k]} ({pct(lv_w[k], len(whys))})" for k in LEVELS) + ' |')
    L.append(f"| Results | {len(results)} | " + ' | '.join(f"{lv_r[k]} ({pct(lv_r[k], len(results))})" for k in LEVELS) + ' |')
    L.append('')
    L.append(f'- Results that reach a why: **{reach} of {len(results)} ({pct(reach, len(results))})**. '
             f'Links: same text {link_types["same-text"]}, same tradition {link_types["same-tradition"]}, '
             f'other tradition {link_types["other-tradition"]}.')
    L.append(f"- Results with a why gap instead: {sum(1 for g in gaps if g['kind'] == 'result-without-why')}.")
    L.append(f'- Restricted results (summary and warnings only): {restricted}.')
    L.append('- Results by kind: ' + ', '.join(f'{k} {v}' for k, v in kinds.most_common()) + '.')
    L.append(f"- Study rows with no entry: {len(empty_study)} of {sum(1 for t in texts if t['tier'] == 'Study')}. "
             f"Read rows with no entry: {len(empty_read)} of {sum(1 for t in texts if t['tier'] == 'Read')}.")
    L.append('')
    L.append('## By engine layer\n')
    L.append('What the engine can stand on. Only `text-verified` and `sourced` entries may reach a person.\n')
    L.append('| Layer | Whys | of which verified or sourced | Results | of which verified or sourced |')
    L.append('|---|---|---|---|---|')
    for t in LAYER_TAGS:
        nw = sum(lay_w[t].values())
        nr = sum(lay_r[t].values())
        gw = lay_w[t]['text-verified'] + lay_w[t]['sourced']
        gr = lay_r[t]['text-verified'] + lay_r[t]['sourced']
        L.append(f'| {t} {LAYER_NAMES[t]} | {nw} | {gw} ({pct(gw, nw)}) | {nr} | {gr} ({pct(gr, nr)}) |')
    L.append('')
    L.append('## By family\n')
    L.append('| Family | Whys | Results |')
    L.append('|---|---|---|')
    for f in sorted(set(fam_w) | set(fam_r), key=lambda x: -(fam_w[x] + fam_r[x])):
        L.append(f'| {f} | {fam_w[f]} | {fam_r[f]} |')
    L.append('')
    L.append('## By row\n')
    L.append('| # | Tier | Text | Feeds | Teachings (tv / s / sk) | Whys | Results | Best level reached |')
    L.append('|---|---|---|---|---|---|---|---|')
    for t in texts:
        tl = t.get('teaching_levels') or {}
        ent = row_w[t['n']] + row_r[t['n']]
        best = '–'
        for k in LEVELS:
            if any(e['verification']['level'] == k for e in ent):
                best = k
                break
        L.append(f"| {t['n']} | {t['tier']} | {t['text'][:70]} | {t['feeds_layer']} | "
                 f"{tl.get('text-verified', 0)} / {tl.get('sourced', 0)} / {tl.get('skeleton', 0)} | "
                 f"{len(row_w[t['n']])} | {len(row_r[t['n']])} | {best} |")
    open(os.path.join(LAYER, 'COVERAGE.md'), 'w').write('\n'.join(L) + '\n')
    # ---- queue
    Q = []
    for t in texts:
        ent = row_w[t['n']] + row_r[t['n']]
        weak = [e for e in ent if e['verification']['level'] in ('skeleton', 'outline')]
        if not weak and ent:
            continue
        engine = t['feeds_layer'] != 'World model only'
        score = (2 if engine else 0) + (1 if t['tier'] == 'Study' else 0)
        cited_skeleton = sorted({c for e in weak for c in e.get('cites') or []})
        hints = sorted({e.get('ref_hint') for e in weak if e.get('ref_hint')})
        Q.append((score, len(weak), t, weak, cited_skeleton, hints))
    Q.sort(key=lambda q: (-q[0], -q[1], q[2]['n']))
    M = ['# Ontology layer: extraction queue\n',
         'Texts whose entries rest on skeleton or outline passages, ranked: engine-feeding Study texts first, then '
         'engine-feeding Read texts, then world-model texts; within each, by how many entries an extraction would upgrade. '
         'Extracting a text (CLAUDE.md, phase D: double extraction and a fidelity check) lifts every entry that cites it.\n',
         '| Rank | # | Tier | Text | Feeds | Weak entries | Passages to extract (cited skeleton teachings / outline locators) |',
         '|---|---|---|---|---|---|---|']
    qjson = []
    for i, (score, nweak, t, weak, cs, hints) in enumerate(Q, 1):
        what = (', '.join(c.split(':', 2)[-1] for c in cs[:8]) + (' …' if len(cs) > 8 else ''))
        if hints:
            what += ('; ' if what else '') + '; '.join(hints[:5]) + (' …' if len(hints) > 5 else '')
        if not weak:
            what = 'no entry yet: the whole text'
        M.append(f"| {i} | {t['n']} | {t['tier']} | {t['text'][:60]} | {t['feeds_layer']} | {nweak} | {what[:300]} |")
        qjson.append({'rank': i, 'n': t['n'], 'tier': t['tier'], 'text': t['text'], 'feeds_layer': t['feeds_layer'],
                      'weak_entries': nweak, 'cited_skeleton_teachings': cs, 'outline_locators': hints,
                      'sources': t['found_sources']})
    open(os.path.join(LAYER, 'QUEUE.md'), 'w').write('\n'.join(M) + '\n')
    with open(os.path.join(LAYER, 'queue.jsonl'), 'w') as f:
        for q in qjson:
            f.write(json.dumps(q, ensure_ascii=False) + '\n')
    json.dump({'whys': len(whys), 'results': len(results), 'whys_by_level': lv_w, 'results_by_level': lv_r,
               'results_reaching_a_why': reach, 'link_types': link_types, 'restricted': restricted,
               'layers_whys': {k: dict(v) for k, v in lay_w.items()}, 'layers_results': {k: dict(v) for k, v in lay_r.items()},
               'empty_study_rows': [t['n'] for t in empty_study], 'empty_read_rows': [t['n'] for t in empty_read],
               'queue_length': len(Q)}, open(os.path.join(LAYER, 'coverage.json'), 'w'), indent=1)
    print(f'COVERAGE.md and QUEUE.md written: {len(whys)} whys, {len(results)} results, queue {len(Q)} texts')


if __name__ == '__main__':
    main()
